COMMENT ON TABLE RUNNER IS '러너 기본 정보 테이블';
COMMENT ON TABLE RUNNER_SOCIAL_ACCOUNT IS '소셜 연동 다중 계정 정보';
COMMENT ON TABLE GARMIN_ACCOUNT_LINK IS '가민 계정 연동 및 동기화 상태 관리';
